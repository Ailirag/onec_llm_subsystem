// Проверка массового режима: из списка выбраны два договора, помощник ставит
// по операции на каждый и показывает пакет; результат применяется по объекту.
// Каждый объект должен уйти в модель со своим файлом: без файла модель
// отвечает пустыми строками, а операция все равно завершается «Готово».
//
// Сценарий ходит в живую базу и обращается к модели дважды, поэтому в обычный
// прогон UI-смоука не входит.
//
//   node run.mjs run http://localhost:8081/do21 tests/ui/batch-queue.mjs

const ЖУРНАЛ = 'H:\\1C\\xml\\LLM_Subsystem_test\\.build\\batch-queue.log';
const ДЕЙСТВИЕ = 'Разобрать пачку договоров';
const проблемы = [];

function лог(текст) {
	const строка = new Date().toISOString().slice(11, 19) + '  ' + текст + '\n';
	try { writeFileSync(ЖУРНАЛ, строка, { flag: 'a' }); } catch (e) { /* журнал не обязателен */ }
	console.log(текст);
}

function проверить(условие, что) {
	лог((условие ? '  [ok]   ' : '  [ФЕЙЛ] ') + что);
	if (!условие) проблемы.push(что);
}

async function дождаться(условие, секунд, описание) {
	лог('жду: ' + описание);
	for (let попытка = 0; попытка * 3 < секунд; попытка += 1) {
		const состояние = await getFormState();
		if (условие(состояние)) {
			return состояние;
		}
		await wait(3);
	}
	лог('  не дождались: ' + JSON.stringify(await getFormState()));
	throw new Error('Не дождались: ' + описание);
}

лог('=== прогон начат ===');

await navigateLink('Справочник.ВнутренниеДокументы');
лог('список открыт');

// Выделяем оба договора папки. Наименования договоров меняет сам разбор
// (заголовок приходит из файла), поэтому строки выбираются не по имени,
// а всем списком.
const строкиСписка = await readTable({ maxRows: 20, table: 'Список' });
if ((строкиСписка.rows || []).length === 0) {
	throw new Error('В списке внутренних документов нет договоров.');
}
// По индексу, а не по тексту: у нового договора наименование бывает пустым.
await clickElement({ row: 0, column: 'Наименование' }, { table: 'Список' });
await getPage().keyboard.press('Control+A');
await wait(1);
const выбранные = (await readTable({ maxRows: 20, table: 'Список' })).rows.filter(р => р._selected);
лог('выбрано договоров: ' + выбранные.length);
проверить(выбранные.length >= 2, 'выбраны два договора');

const список = await getFormState();
const подменю = (список.buttons || [])
	.map(к => (typeof к === 'string' ? к : к.name))
	.find(и => и && и.indexOf('ПодменюЗаполнить') === 0);
лог('кнопки списка: ' + JSON.stringify((список.buttons || []).map(к => (typeof к === 'string' ? к : к.name))));
if (!подменю) {
	throw new Error('В форме списка нет подменю помощника.');
}
await clickElement(подменю);

// Из формы списка БСП сначала показывает свой список зарегистрированных
// обработок: помощник запускается второй командой, а не сразу.
const послеПодменю = await getFormState();
const кнопкиБСП = (послеПодменю.buttons || [])
	.map(к => (typeof к === 'string' ? к : к.name));
if (кнопкиБСП.indexOf('Выполнить') >= 0) {
	лог('БСП показала список обработок — запускаю помощника');
	// Клик по строке обработки БСП уже запускает ее; кнопка «Выполнить»
	// остается запасным путем и может исчезнуть вместе с диалогом.
	await clickElement('AI-помощник');
	try {
		await clickElement('Выполнить');
	} catch (e) {
		лог('диалог БСП закрылся сам');
	}
	await wait(2);
}
лог('помощник открыт из списка');

const действия = await readTable({ maxRows: 20 });
лог('действия: ' + JSON.stringify((действия.rows || []).map(р => р[(действия.columns || [])[0]])));

await clickElement(ДЕЙСТВИЕ);
await wait(1);
// Уточнений у пакетного действия нет, поэтому выбор строки сразу запускает
// очередь. Кнопку жмем, только если мастер все-таки ее показал.
try {
	await clickElement('Далее');
	лог('нажато: Далее');
} catch (e) {
	лог('мастер ушел к пакету без «Далее»');
}
лог('пакет запущен');

const готово = await дождаться(
	состояние => {
		const таблицы = состояние.tables || [];
		return таблицы.some(т => т.name === 'Пакет');
	},
	30,
	'появление списка пакета');
проверить(true, 'помощник показал страницу пакета');

const пакет = await readTable({ maxRows: 20, table: 'Пакет' });
лог('строки пакета: ' + JSON.stringify(пакет.rows || []));
проверить((пакет.rows || []).length === 2, 'в пакете две строки');

// Ждем, пока очередь разберет оба объекта. Опрос делает сама форма, нам
// остается смотреть на колонку состояния.
async function строкиПакета() {
	const таблица = await readTable({ maxRows: 20, table: 'Пакет' });
	return таблица.rows || [];
}

let итоговые = [];
for (let попытка = 0; попытка < 60; попытка += 1) {
	итоговые = await строкиПакета();
	const состояния = итоговые.map(р => String(р['Состояние'] || ''));
	if (состояния.length > 0 && состояния.every(с => /Готово|Ошибка|не удалось/i.test(с))) {
		break;
	}
	await wait(3);
}
лог('итог пакета: ' + JSON.stringify(итоговые));
проверить(итоговые.length === 2 && итоговые.every(р => /Готово/i.test(String(р['Состояние'] || ''))),
	'обе операции пакета завершились успешно');
// Без файла модель отвечает пустотой, и операция все равно «Готово»:
// поэтому проверяется, что каждый объект ушел со своим файлом.
проверить(итоговые.every(р => String(р['Файл'] || '').length > 0),
	'у каждого объекта пакета взят свой файл: ' + JSON.stringify(итоговые.map(р => р['Файл'])));

// Открываем первый объект и применяем действие именно к нему.
await clickElement({ row: 0, column: 'Объект' }, { table: 'Пакет' });
await clickElement('Открыть результат');
лог('открыт результат первого объекта');

const результат = await getFormState();
const поля = JSON.stringify(результат.fields || []);
проверить(поля.indexOf('Анализ завершен') >= 0 && поля.indexOf('Распознано') >= 0,
	'на странице результата показан разбор: ' + поля);

// Значения должны прийти из файла, а не пустыми строками: пустое модель
// возвращает, когда документа не видела.
const рекомендации = await readTable({ maxRows: 40, table: 'Рекомендации' });
const непустые = (рекомендации.rows || []).filter(р => String(р['Предлагается'] || '').length > 0);
лог('непустых значений: ' + непустые.length + ' из ' + (рекомендации.rows || []).length);
проверить(непустые.length >= 5, 'модель нашла значения в файле объекта');

// Значения, совпадающие с объектом, не отмечаются. Если отмечать нечего —
// отмечаем первую строку сами: проверяется путь применения, а не изменение.
if (!(рекомендации.rows || []).some(р => String(р['Применить']) === 'true')) {
	await clickElement({ row: 0, column: 'Применить' }, { table: 'Рекомендации' });
	лог('отмечена первая строка: все значения совпадали с объектом');
}

// Подпись кнопки действия задается настройкой места запуска и может быть
// любой, поэтому ищем ее «от противного» — как единственную, не входящую в
// постоянный состав мастера.
const служебные = ['Еще', '< Назад', 'Далее >', 'Далее', 'Открыть диалог', 'Закрыть',
	'Выгрузить пакет', 'Загрузить пакет', 'Открыть результат', 'Записать объект',
	'Основное', 'Процессы и задачи', 'Переписка', 'Журнал передачи'];
const кнопкаДействия = (результат.buttons || [])
	.map(к => (typeof к === 'string' ? к : к.name))
	.filter(и => и && служебные.indexOf(и) < 0 && и.indexOf('Подменю') < 0
		&& и.indexOf('Группа') < 0 && и.indexOf('Форма') < 0)[0];
проверить(!!кнопкаДействия, 'на результате есть кнопка действия: ' + кнопкаДействия);

if (кнопкаДействия) {
	await clickElement(кнопкаДействия);
	await clickElement('Да');
	const применено = await дождаться(
		состояние => JSON.stringify(состояние.fields || []).indexOf('Применено') >= 0,
		60,
		'применение действия к объекту пакета');
	лог('применение: ' + JSON.stringify(применено.fields || []));
	проверить(!/Применено: 0,/.test(JSON.stringify(применено.fields || [])),
		'действие применено к выбранному объекту пакета');
}

// Возврат должен вести обратно к пакету, а не к списку действий.
await clickElement('< Назад');
const назад = await getFormState();
проверить((назад.tables || []).some(т => т.name === 'Пакет'),
	'из результата возвращаемся к списку пакета');

// Окно команд БСП закрывается при запуске помощника: после помощника человек
// возвращается к списку, а не к окну выбора обработок.
await clickElement('Закрыть');
await wait(1);
const послеПомощника = await getFormState();
проверить(String(послеПомощника.title || '').indexOf('Команды заполнения') < 0,
	'после помощника не осталось окна команд БСП: ' + послеПомощника.title);

лог('');
if (проблемы.length > 0) {
	throw new Error('Провалов: ' + проблемы.length + ' — ' + проблемы.join('; '));
}
лог('[OK] Массовый режим работает.');
