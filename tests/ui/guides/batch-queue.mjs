// Инструкция: разбор пачки договоров одним вызовом помощника.
//
// Запускается вручную этапом tools\Build-UserGuide.ps1. Механика снимков живет
// в _runtime.mjs и подставляется перед этим текстом. Имена по умолчанию —
// стенда Документооборота; на другой базе их передают ключом -Parameters:
//
//   список    — список, где лежат договоры;
//   документы — по тексту из строки каждого договора, который войдет в пачку.
//               У второго договора стенда нет номера, его строка находится по
//               дате;
//   действие  — подпись пакетного действия в помощнике.
//
// Результат по договору записывается в базу, поэтому без -ApplyResults
// инструкция снимает кнопку записи, но не нажимает ее.

const ЗАГОЛОВОК = 'Разбор пачки договоров AI-помощником';
const СПИСОК = параметр('список', 'Справочник.ВнутренниеДокументы');
const ДОКУМЕНТЫ = [].concat(параметр('документы', ['ПСТ-2026/417', '23.09.2026']));
const ДЕЙСТВИЕ = параметр('действие', 'Разобрать пачку договоров');

await navigateLink(СПИСОК);
await снимок(
	'Откройте список документов',
	null,
	'Массовый разбор начинается со списка: помощник возьмет те документы, которые вы выделите.');

for (let номер = 0; номер < ДОКУМЕНТЫ.length; номер += 1) {
	try {
		if (номер === 0) {
			await clickElement(ДОКУМЕНТЫ[номер]);
		} else {
			await clickElement(ДОКУМЕНТЫ[номер], { modifier: 'ctrl' });
		}
	} catch (e) {
		throw new Error('В списке нет строки «' + ДОКУМЕНТЫ[номер] + '». Передайте свои:'
			+ ' -Parameters @{ \'документы\' = @(\'…\', \'…\') }.');
	}
}
await снимок(
	'Выделите нужные документы',
	null,
	'Несколько строк выделяются мышью с Ctrl или Shift. Помощник обработает ровно их.');

const состояниеСписка = await getFormState();
const подменю = (состояниеСписка.buttons || [])
	.map(к => (typeof к === 'string' ? к : к.name))
	.find(и => и && и.indexOf('ПодменюЗаполнить') === 0);
if (!подменю) {
	throw new Error('В форме списка нет подменю помощника.');
}

await снимок(
	'Вызовите помощника',
	подменю,
	'Команда живет в том же подменю дополнительных обработок, что и в карточке документа.');
await clickElement(подменю);

// Из формы списка БСП сначала показывает свой список зарегистрированных
// обработок: помощник запускается второй командой.
const послеПодменю = await getFormState();
const кнопкиБСП = (послеПодменю.buttons || []).map(к => (typeof к === 'string' ? к : к.name));
if (кнопкиБСП.indexOf('Выполнить') >= 0) {
	await снимок(
		'Выберите обработку «AI-помощник»',
		'AI-помощник',
		'Этот список показывает сама конфигурация: в нем перечислены все дополнительные обработки,'
		+ ' подключенные к форме списка.');
	await clickElement('AI-помощник');
	await попробоватьКлик('Выполнить');
	await wait(2);
}

await проверитьДействие(ДЕЙСТВИЕ);
await снимок(
	'Выберите действие',
	ДЕЙСТВИЕ,
	'В списке только те действия, которые настроены на несколько объектов сразу.');
await clickElement(ДЕЙСТВИЕ);
await wait(2);
const вперед = await кнопкаВперед();
if (вперед) {
	await clickElement(вперед);
}

await снимок(
	'Дождитесь, пока очередь разберет объекты',
	null,
	'На каждый документ ставится своя операция: они выполняются фоновыми заданиями и не блокируют интерфейс.'
	+ ' Ошибка по одному документу не отменяет остальные — она останется в его строке.');

// Ждем, пока все строки пакета дойдут до конечного состояния.
let строки = [];
for (let попытка = 0; попытка < 40; попытка += 1) {
	const таблица = await readTable({ maxRows: 20, table: 'Пакет' });
	строки = таблица.rows || [];
	const состояния = строки.map(р => String(р['Состояние'] || ''));
	if (состояния.length > 0 && состояния.every(с => /Готово|Ошибка|Пропущен|не удалось/i.test(с))) {
		break;
	}
	await wait(3);
}

await снимок(
	'Проверьте состояние по каждому документу',
	null,
	'Колонка состояния показывает, что произошло с каждым документом по отдельности.');

if (строки.length > 0) {
	await clickElement(String(строки[0]['Объект']));
	await снимок(
		'Откройте результат по документу',
		'Открыть результат',
		'Дальше все как при работе с одним документом: те же предложенные значения и то же решение за вами.');
	await clickElement('Открыть результат');
	await wait(2);

	await снимок(
		'Проверьте предложенные значения',
		null,
		'Отметки снимаются по строкам. Результат применяется только к тому документу, который вы открыли.');

	const кнопкаДействия = await кнопкаДействияМастера();
	if (кнопкаДействия && можноНажатьДействие(кнопкаДействия)) {
		await снимок('Примените результат', кнопкаДействия);
		await clickElement(кнопкаДействия);
		await попробоватьКлик('Да');
		await wait(4);
		await снимок(
			'Готово по документу',
			null,
			'В строке состояния виден итог. Кнопка «< Назад» возвращает к списку пачки — к следующему документу.');
	} else if (кнопкаДействия) {
		await снимок(
			'Примените результат',
			кнопкаДействия,
			'«' + кнопкаДействия + '» записывает отмеченные значения в документ. При сборке этой инструкции'
			+ ' кнопка не нажималась: данные базы не менялись. Кнопка «< Назад» возвращает к списку пачки —'
			+ ' к следующему документу.');
	}
}

сохранитьИнструкцию(ЗАГОЛОВОК);
