// Проверка встроенной справки (F1) во всех формах подсистемы.
//
// Для каждой формы: F1 открывает страницу с ожидаемым заголовком, картинки
// страницы загружены, каждая ссылка на другую страницу открывается. Ссылка
// проверяется запросом по ее адресу — с параметрами сеанса, которые к ней
// дописывает скрипт session-links (его вставляет tools/Update-HelpPages.ps1).
// Отдельно проверяются ссылки обзора подсистемы. Найдены ошибки — сценарий
// завершается с ошибкой.
//
// Работает в любой базе с расширением: формы открываются без данных.
//
//   node run.mjs run http://localhost:8081/<публикация> tests/ui/help-check.mjs

