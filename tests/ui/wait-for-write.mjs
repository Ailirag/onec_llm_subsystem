if (!подменю) {
	throw new Error('В карточке нет подменю «Заполнить» — обработка не зарегистрирована.');
}
await clickElement(подменю);
лог('помощник открыт');

// --- шаг 1: заполнение формы делает карточку измененной ---------------------

await выполнитьДействие(ДЕЙСТВИЕ_ЗАПОЛНЕНИЯ, '(текст)');
const послеЗаполнения = await дождаться(
	текст => текст.indexOf('Заполнено') >= 0 || текст.indexOf('Применено') >= 0
		|| текст.indexOf('не приняла') >= 0,
	60,
	'итог заполнения формы');
лог('заполнение формы: ' + послеЗаполнения);

проверить(await вернутьсяКСписку(), 'из результата можно вернуться к списку действий');

// --- шаг 2: действие с ожиданием записи -------------------------------------

await выполнитьДействие(ДЕЙСТВИЕ_ОЖИДАНИЯ);
const ожидание = await дождаться(
	текст => текст.indexOf('Запишите') >= 0 || текст.indexOf('Ожидание записи') >= 0,
	30,
	'переход помощника в ожидание записи');
проверить(true, 'помощник ждет записи: ' + ожидание);

// Карточка остается заблокированной окном помощника — это свойство платформы,
// снять его на ходу нельзя. Поэтому запись предлагает сам помощник, и проверяем
// мы именно его кнопку.
const страница = getPage();
const кнопкаКарточки = await страница.evaluate(найтиКнопку, 'Записать');
лог('кнопка карточки: ' + JSON.stringify(кнопкаКарточки));
проверить(кнопкаКарточки.доступна !== true,
	'карточка ожидаемо закрыта модальным окном помощника');

const состояниеОжидания = await getFormState();
const естьКнопка = (состояниеОжидания.buttons || [])
	.map(к => (typeof к === 'string' ? к : к.name))
	.some(и => и === 'Записать объект');
проверить(естьКнопка, 'помощник предлагает кнопку «Записать объект»');
if (естьКнопка) {
	await clickElement('Записать объект');
	лог('кнопка «Записать объект» нажата');
}

const итог = await дождаться(
	текст => текст.indexOf('Применено') >= 0 || текст.indexOf('не появился') >= 0
		|| текст.indexOf('не продолжено') >= 0 || текст.indexOf('остановлено') >= 0,
	120,
	'продолжение после записи');
проверить(итог.indexOf('Применено') >= 0, 'действие продолжено после записи: ' + итог);

лог('');
if (проблемы.length > 0) {
	throw new Error('Провалов: ' + проблемы.length + ' — ' + проблемы.join('; '));
}
лог('[OK] Ожидание записи работает.');
