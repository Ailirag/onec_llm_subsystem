// Инструкция: создание набора знаний и его назначение агенту или сценарию.
//
// Сценарий работает на пустых новых формах и ничего не записывает в базу.

const title = 'Как настроить наборы знаний для агента и сценария';

await openLink('Справочник.AI_НаборыЗнаний', 'Наборы знаний');
await step(
  'Откройте «Наборы знаний»',
  'Создать',
  'Набор объединяет карточку предприятия, банковские реквизиты и другие блоки контекста, которые назначаются вместе.');

await clickElement('Создать');
await step(
  'Заполните карточку набора',
  null,
  'Укажите понятное наименование, уникальный программный идентификатор, назначение, версию и дату актуальности. Флаг «Активен» управляет использованием всего набора.');

await step(
  'Добавьте карточки в состав',
  'Добавить',
  'Карточки передаются модели по порядку строк. Одну карточку нельзя включить в набор дважды. Для больших документов используйте RAG.');
await closeForm({ save: false });

await openLink('Справочник.AI_Агенты', 'Агенты');
await clickElement('Создать');
await clickElement('Знания');
await step(
  'Назначьте общие знания агенту',
  'Добавить',
  'Все активные наборы на этой вкладке применяются в операциях агента. Единичные карточки остаются на вкладке «Отдельные контексты».');
await closeForm({ save: false });

await openLink('Справочник.AI_Сценарии', 'Сценарии');
await clickElement('Создать');
await clickElement('Знания');
await step(
  'При необходимости уточните знания в сценарии',
  'Добавить',
  'Наборы сценария действуют только при его выполнении. Карточка сценария с тем же программным идентификатором заменяет карточку агента.');
await closeForm({ save: false });

saveGuide(title);
