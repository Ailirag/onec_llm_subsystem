// Инструкция: заполнение реквизитов договора помощником.
//
// Запускается вручную этапом tools\Build-UserGuide.ps1, а не вместе с тестами:
// он ходит в базу, обращается к модели и занимает минуты.
//
// Механика снимков и сборки HTML живет в _runtime.mjs и подставляется перед
// этим текстом, поэтому здесь только шаги. Имена по умолчанию — стенда
// Документооборота; на другой базе их передают ключом -Parameters:
//
//   список   — список, где лежит договор;
//   документ — текст из строки договора: регистрационный номер надежнее
//              наименования, одинаковых «Договор поставки» бывает несколько;
//   действие — подпись действия в помощнике, как в месте запуска.

const ЗАГОЛОВОК = 'Заполнение реквизитов договора AI-помощником';
const СПИСОК = параметр('список', 'Справочник.ВнутренниеДокументы');
const ДОКУМЕНТ = параметр('документ', 'ПСТ-2026/417');
const ДЕЙСТВИЕ = параметр('действие', 'Извлечь реквизиты из файла');

await navigateLink(СПИСОК);
await снимок(
	'Откройте список документов и найдите нужный договор',
	null,
	'Помощник вызывается из карточки объекта, поэтому начинаем со списка.');

try {
	await clickElement(ДОКУМЕНТ, { dblclick: true });
} catch (e) {
	throw new Error('В списке нет договора «' + ДОКУМЕНТ + '». Передайте свой: -Parameters @{ \'документ\' = \'…\' }.');
}
await попробоватьКлик('Напомнить позже');
await снимок(
	'Откройте карточку договора',
	null,
	'В карточке видны присоединенные файлы — именно из них помощник возьмет данные.');

// Команда помощника живет в подменю «Заполнить» механизма дополнительных
// обработок. Имя подменю конфигурация генерирует с хешем, поэтому ищем его по
// устойчивому началу, а не по полному имени.
const состояниеКарточки = await getFormState();
const подменюЗаполнить = (состояниеКарточки.buttons || [])
	.map(кнопка => (typeof кнопка === 'string' ? кнопка : кнопка.name))
	.find(имя => имя && имя.indexOf('ПодменюЗаполнить') === 0);
if (!подменюЗаполнить) {
	throw new Error('В карточке нет подменю «Заполнить» — обработка помощника не зарегистрирована.');
}

await снимок(
	'Нажмите кнопку вызова помощника',
	подменюЗаполнить,
	'Помощник подключается механизмом дополнительных обработок и появляется в подменю «Заполнить».');
await clickElement(подменюЗаполнить);
await wait(1);

await проверитьДействие(ДЕЙСТВИЕ);
await снимок(
	'Выберите действие',
	ДЕЙСТВИЕ,
	'Список показывает только действия, настроенные для этого вида документа.'
	+ ' Выбор строки сразу ведет к уточняющим вопросам.');
await clickElement(ДЕЙСТВИЕ);
await wait(1);

// Уточнений бывает несколько: «Далее >» ведет к следующему, а на последнем
// кнопка называется «Запустить анализ». Подпись шага берем с самой кнопки.
for (let уточнение = 0; уточнение < 5; уточнение += 1) {
	const вперед = await кнопкаВперед();
	if (!вперед) {
		break;
	}
	const последнее = вперед !== 'Далее >' && вперед !== 'Далее';
	await снимок(
		уточнение === 0 ? 'Выберите файл и нажмите «' + вперед + '»' : 'Ответьте на вопрос и нажмите «' + вперед + '»',
		вперед,
		уточнение === 0
			? 'Помощник показывает только файлы, подходящие по настроенному отбору.'
			: 'Помощник задает только те вопросы, которые настроены для действия.');
	await clickElement(вперед);
	await wait(1);
	if (последнее) {
		break;
	}
}

await wait(5);
await снимок(
	'Дождитесь ответа модели',
	null,
	'Интерфейс не блокируется: рядом с состоянием крутится индикатор и идет счетчик времени.'
	+ ' Обращение к модели выполняется фоновым заданием.');

// Модель отвечает по-разному: на длинном договоре бывает и полторы минуты.
// Ждем с запасом — инструкция должна собираться одинаково, а не через раз.
for (let попытка = 0; попытка < 36; попытка += 1) {
	const состояние = await getFormState();
	const текст = JSON.stringify(состояние.fields || []);
	if (текст.indexOf('Анализ завершен') >= 0 || текст.indexOf('ошибкой') >= 0) {
		break;
	}
	await wait(5);
}

await снимок(
	'Проверьте предложенные значения',
	null,
	'Снимите отметку с тех строк, которые применять не нужно. Модель ничего не решает: решение за вами.');

const кнопкаДействия = await кнопкаДействияМастера();
if (!кнопкаДействия) {
	throw new Error('На странице результата нет кнопки действия.');
}

if (!можноНажатьДействие(кнопкаДействия)) {
	await снимок(
		'Нажмите «' + кнопкаДействия + '»',
		кнопкаДействия,
		'Кнопка записывает значения в базу, поэтому при сборке этой инструкции она не нажималась:'
		+ ' снимки сделаны без изменения данных.');
} else {
	await снимок('Нажмите «' + кнопкаДействия + '»', кнопкаДействия);
	await clickElement(кнопкаДействия);

	await снимок(
		'Подтвердите действие',
		'Да',
		'Текст вопроса прямо говорит, будет объект записан или нет.');
	await clickElement('Да');

	await wait(3);
	const послеПодтверждения = await getFormState();
	const текстПосле = JSON.stringify(послеПодтверждения.fields || []);

	if (текстПосле.indexOf('Запишите') >= 0 || текстПосле.indexOf('Ожидание записи') >= 0) {
		// Действию нужна ссылка на объект, а у незаписанного объекта ее нет.
		await снимок(
			'Запишите объект',
			'Записать объект',
			'Действию нужна ссылка на объект, а она появляется только при записи.'
			+ ' Помощник ждет и предлагает записать — записывает форма объекта,'
			+ ' со всеми своими проверками.'
			+ (записыватьВБазу ? '' : ' При сборке этой инструкции объект не записывался.'));
		if (записыватьВБазу) {
			await попробоватьКлик('Записать объект');
			await wait(4);
		}
	} else if (послеПодтверждения.confirmation) {
		await снимок(
			'Ответьте на уточняющий вопрос',
			'Да',
			'Действие может быть многошаговым: обработчик вправе спросить и продолжить после ответа.');
		await clickElement('Да');
		await wait(3);
	}

	await снимок(
		'Готово',
		null,
		'В строке состояния виден итог, а сообщения внизу показывают, что именно сделано.');
}

сохранитьИнструкцию(ЗАГОЛОВОК);
