// Проверка цепочки действий: обработчик предлагает продолжить другим местом
// запуска, помощник спрашивает человека и переходит к нему.
//
// Сценарий ходит в живую базу и обращается к модели, поэтому в обычный прогон
// UI-смоука не входит.
//
//   node run.mjs run http://localhost:8081/do21 tests/ui/action-chain.mjs

const ЖУРНАЛ = 'H:\\1C\\xml\\LLM_Subsystem_test\\.build\\action-chain.log';
const ДЕЙСТВИЕ = 'Заполнить реквизиты по файлу';
const проблемы = [];

function лог(текст) {
	const строка = new Date().toISOString().slice(11, 19) + '  ' + текст + '\n';
	try { writeFileSync(ЖУРНАЛ, строка, { flag: 'a' }); } catch (e) { /* журнал не обязателен */ }
	console.log(текст);
}

function проверить(условие, что) {
	лог((условие ? '  [ok]   ' : '  [ФЕЙЛ] ') + что);
	if (!условие) проблемы.push(что);
}

async function дождаться(условие, секунд, описание) {
	лог('жду: ' + описание);
	for (let попытка = 0; попытка * 2 < секунд; попытка += 1) {
		const состояние = await getFormState();
		if (условие(JSON.stringify(состояние))) {
			return состояние;
		}
		await wait(2);
	}
	лог('  не дождались: ' + JSON.stringify(await getFormState()));
	throw new Error('Не дождались: ' + описание);
}

лог('=== прогон начат ===');

await navigateLink('Справочник.ВнутренниеДокументы');
await clickElement('Договор поставки', { dblclick: true });
try { await clickElement('Напомнить позже'); } catch (e) { /* подсказка не всегда */ }

const карточка = await getFormState();
const подменю = (карточка.buttons || [])
	.map(к => (typeof к === 'string' ? к : к.name))
	.find(и => и && и.indexOf('ПодменюЗаполнить') === 0);
if (!подменю) {
	throw new Error('В карточке нет подменю помощника.');
}
await clickElement(подменю);
лог('помощник открыт');

await clickElement(ДЕЙСТВИЕ);
await wait(1);
for (const кнопка of ['Далее', 'Запустить анализ']) {
	try {
		await clickElement(кнопка);
		break;
	} catch (e) { /* мастер мог уйти дальше сам */ }
}

await дождаться(текст => текст.indexOf('Анализ завершен') >= 0, 150, 'ответ модели');

const результат = await getFormState();
// Подпись кнопки действия задается настройкой места запуска и может быть
// любой, поэтому ищем ее «от противного» — как единственную, не входящую в
// постоянный состав мастера.
const служебные = ['Еще', '< Назад', 'Далее >', 'Далее', 'Открыть диалог', 'Закрыть',
	'Выгрузить пакет', 'Загрузить пакет', 'Открыть результат', 'Записать объект',
	'Основное', 'Процессы и задачи', 'Переписка', 'Журнал передачи'];
const кнопкаДействия = (результат.buttons || [])
	.map(к => (typeof к === 'string' ? к : к.name))
	.filter(и => и && служебные.indexOf(и) < 0 && и.indexOf('Подменю') < 0
		&& и.indexOf('Группа') < 0 && и.indexOf('Форма') < 0)[0];
if (!кнопкаДействия) {
	throw new Error('Нет кнопки действия: ' + JSON.stringify(результат.buttons || []));
}
await clickElement(кнопкаДействия);
await clickElement('Да');
лог('действие выполнено');

// Предложение цепочки приходит вопросом сразу после завершения действия.
const вопрос = await дождаться(
	текст => текст.indexOf('Продолжить действием') >= 0 || текст.indexOf('другому основному') >= 0,
	20,
	'вопрос о продолжении цепочки');
лог('вопрос: ' + JSON.stringify(вопрос.confirmation || вопрос.fields || []));
проверить(true, 'помощник предложил продолжить цепочку');

await clickElement('Да');
лог('согласие на продолжение');

// После перехода мастер показывает следующее действие: у него свое уточнение
// с выбором файла, то есть мы ушли со страницы результата.
const после = await дождаться(
	текст => текст.indexOf('Уточнение') >= 0 || текст.indexOf('Выберите') >= 0
		|| текст.indexOf('Анализ выполняется') >= 0 || текст.indexOf('Анализ завершен') >= 0,
	60,
	'переход к следующему действию');
лог('после перехода: ' + JSON.stringify(после.fields || []));
проверить(true, 'помощник перешел к следующему действию');

лог('');
if (проблемы.length > 0) {
	throw new Error('Провалов: ' + проблемы.length + ' — ' + проблемы.join('; '));
}
лог('[OK] Цепочка действий работает в интерфейсе.');
