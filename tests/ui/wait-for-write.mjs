// Проверка шага «ОжиданиеЗаписи»: обработчик просит дождаться записи объекта,
// помощник отпускает окно карточки, человек записывает, действие продолжается.
//
// Сценарий ходит в живую базу и обращается к модели дважды, поэтому в обычный
// прогон UI-смоука не входит: запускается руками при правке этой ветки кода.
//
//   node run.mjs run http://localhost:8081/do21 tests/ui/wait-for-write.mjs
//
// Порядок неочевиден и выбран осознанно. Ожидание записи имеет смысл только у
// измененной карточки: у записанного и неизмененного объекта ссылка уже есть,
// и шаг проходит мгновенно. Изменить карточку до вызова помощника нельзя —
// Документооборот сам потребует записать документ перед запуском обработки.
// Поэтому карточку изменяет первое действие помощника (заполнение формы), а
// ожидание проверяет второе.
//
// Кнопку записи ищем и нажимаем через DOM: при открытом помощнике раннер
// считает текущей его форму, и кнопок карточки для него «не существует». Нам
// же нужно проверить ровно обратное — что они доступны человеку.

const ЖУРНАЛ = 'H:\\1C\\xml\\LLM_Subsystem_test\\.build\\wait-for-write.log';
const ДЕЙСТВИЕ_ЗАПОЛНЕНИЯ = 'Извлечь реквизиты из файла';
const ДЕЙСТВИЕ_ОЖИДАНИЯ = 'Заполнить реквизиты по файлу';
const проблемы = [];

function лог(текст) {
	const строка = new Date().toISOString().slice(11, 19) + '  ' + текст + '\n';
	try { writeFileSync(ЖУРНАЛ, строка, { flag: 'a' }); } catch (e) { /* журнал не обязателен */ }
	console.log(текст);
}

function проверить(условие, что) {
	лог((условие ? '  [ok]   ' : '  [ФЕЙЛ] ') + что);
	if (!условие) проблемы.push(что);
}

function текстСостояния(состояние) {
	return JSON.stringify(состояние.fields || []);
}

async function дождаться(условие, секунд, описание) {
	лог('жду: ' + описание);
	for (let попытка = 0; попытка * 2 < секунд; попытка += 1) {
		const состояние = await getFormState();
		const текст = текстСостояния(состояние);
		if (условие(текст, состояние)) {
			return текст;
		}
		await wait(2);
	}
	лог('  не дождались, состояние: ' + текстСостояния(await getFormState()));
	throw new Error('Не дождались: ' + описание);
}

// Ищет видимую кнопку по тексту и докладывает, перекрыта ли она сверху.
// Перекрытие и означает «окно владельца заблокировано».
function найтиКнопку(подпись) {
	const узлы = [...document.querySelectorAll('div,span,a,td')].filter(узел =>
		узел.children.length === 0 &&
		(узел.innerText || '').trim() === подпись &&
		узел.offsetWidth > 0 && узел.offsetHeight > 0);
	if (узлы.length === 0) {
		return { найдена: false };
	}
	const r = узлы[0].getBoundingClientRect();
	const точка = { x: r.left + r.width / 2, y: r.top + r.height / 2 };
	const сверху = document.elementFromPoint(точка.x, точка.y);
	const доступна = !!сверху
		&& (сверху === узлы[0] || узлы[0].contains(сверху) || сверху.contains(узлы[0]));
	return {
		найдена: true,
		доступна: доступна,
		точка: точка,
		сверху: сверху ? (сверху.tagName + '.' + (сверху.className || '')).slice(0, 60) : null,
	};
}

async function вернутьсяКСписку() {
	for (let попытка = 0; попытка < 4; попытка += 1) {
		const состояние = await getFormState();
		const таблицы = состояние.tables || [];
		if (таблицы.some(т => т.name === 'Сценарии')) {
			return true;
		}
		try {
			await clickElement('< Назад');
		} catch (e) {
			return false;
		}
	}
	return false;
}

async function выполнитьДействие(имя, файл) {
	await clickElement(имя);
	await wait(1);
	if (файл) {
		// У места запуска без отбора по расширению первым в списке лежит PDF,
		// а его распознавание упирается в права ключа провайдера. Проверка не
		// про OCR, поэтому берем текстовое вложение явно — по содержимому
		// строки таблицы, а не по обрывку текста: поиск кликом его не находит.
		const список = await readTable({ maxRows: 20 });
		const колонка = (список.columns || [])[0];
		const строка = (список.rows || [])
			.find(р => String(р[колонка] || '').indexOf(файл) >= 0);
		if (строка) {
			await clickElement(String(строка[колонка]));
			лог('выбран файл: ' + строка[колонка]);
		} else {
			лог('файл с «' + файл + '» не найден: ' + JSON.stringify(список.rows || []));
		}
	}
	// Выбор строки в списке файлов мастер может принять как ответ и сам уйти
	// на следующий шаг. Поэтому кнопку жмем «если она есть», а не вслепую.
	for (const кнопка of ['Далее', 'Запустить анализ']) {
		try {
			await clickElement(кнопка);
			лог('нажато: ' + кнопка);
			break;
		} catch (e) {
			лог('кнопки «' + кнопка + '» нет, иду дальше');
		}
	}
	await дождаться(текст => текст.indexOf('Анализ завершен') >= 0, 150, 'ответ модели (' + имя + ')');
	// Подпись кнопки действия задается настройкой места запуска и может быть
	// любой, поэтому ищем ее «от противного» — как единственную, не входящую
	// в постоянный состав мастера.
	const служебные = ['Еще', '< Назад', 'Далее >', 'Далее', 'Открыть диалог', 'Закрыть',
		'Выгрузить пакет', 'Загрузить пакет', 'Открыть результат', 'Записать объект',
		'Основное', 'Процессы и задачи', 'Переписка', 'Журнал передачи'];
	const результат = await getFormState();
	const кнопкаДействия = (результат.buttons || [])
		.map(к => (typeof к === 'string' ? к : к.name))
		.filter(и => и && служебные.indexOf(и) < 0 && и.indexOf('Подменю') < 0
			&& и.indexOf('Группа') < 0 && и.indexOf('Форма') < 0)[0];
	if (!кнопкаДействия) {
		throw new Error('На странице результата нет кнопки действия: '
			+ JSON.stringify(результат.buttons || []));
	}
	лог('кнопка действия: ' + кнопкаДействия);
	await clickElement(кнопкаДействия);
	await clickElement('Да');
}

лог('=== прогон начат ===');

await navigateLink('Справочник.ВнутренниеДокументы');
await clickElement('Договор поставки', { dblclick: true });
try { await clickElement('Напомнить позже'); } catch (e) { /* подсказка не всегда */ }
лог('карточка открыта');

const карточка = await getFormState();
const подменю = (карточка.buttons || [])
	.map(кнопка => (typeof кнопка === 'string' ? кнопка : кнопка.name))
