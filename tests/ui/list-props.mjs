// Проверка дополнительных реквизитов-списков: модель выбирает значения из
// перечня в схеме, помощник показывает их, а действие кладет в договор
// значения именно тех свойств, которые входят в наборы самого договора.
//
// Две фазы:
//   1. «Заполнить форму»: свойства должны появиться в карточке и пережить
//      запись. Форма БСП собирает свойства из своих реквизитов, и значение,
//      положенное мимо них, при записи пропадает — это и проверяется;
//   2. «Записать в объект»: запись проходит без отказов по одноименным
//      свойствам и без чужих значений.
//
// Сценарий ходит в живую базу и обращается к модели, поэтому в обычный прогон
// UI-смоука не входит: запускается руками при правке этой ветки кода.
//
//   node run.mjs run http://localhost:8081/do21 tests/ui/list-props.mjs
//
// Перед прогоном у вида документа «Договор» должен быть свой набор свойств со
// свойствами-списками «Тип договора», «Соглашение о зачете», «Закупка товара
// для перепродажи», «Сумма фин. рисков» и булевым «инициатор=менеджер», а
// одноименное «инициатор=менеджер» — в чужом наборе. Карта «Реквизиты
// договора» должна содержать поля этих свойств, а схема — быть перенесена в
// сценарий (команда «Записать схему в сценарии» на форме карты).

const ЖУРНАЛ = 'H:\\1C\\xml\\LLM_Subsystem_test\\.build\\list-props.log';
const ДЕЙСТВИЕ_ФОРМЫ = 'Извлечь реквизиты из файла';
const ДЕЙСТВИЕ_ЗАПИСИ = 'Разобрать пачку договоров';
const СВОЙСТВА = ['Тип договора', 'Соглашение о зачете', 'Закупка для перепродажи',
	'Сумма фин. рисков', 'Инициатор — менеджер'];
// Подпись поля в карте -> подпись поля свойства в карточке договора.
// Булево свойство не сверяется: его «Нет» не отличить от незаполненного.
const ПОЛЯ_КАРТОЧКИ = {
	'Тип договора': 'Тип договора',
	'Соглашение о зачете': 'Соглашение о зачете',
	'Закупка для перепродажи': 'Закупка товара для перепродажи',
	'Сумма фин. рисков': 'Сумма фин. рисков'
};
const проблемы = [];

function лог(текст) {
	const строка = new Date().toISOString().slice(11, 19) + '  ' + текст + '\n';
	try { writeFileSync(ЖУРНАЛ, строка, { flag: 'a' }); } catch (e) { /* журнал не обязателен */ }
	console.log(текст);
}

function проверить(условие, что) {
	лог((условие ? '  [ok]   ' : '  [ФЕЙЛ] ') + что);
	if (!условие) проблемы.push(что);
}

function текстСостояния(состояние) {
	return JSON.stringify(состояние.fields || []);
}

async function дождаться(условие, секунд, описание) {
	лог('жду: ' + описание);
	for (let попытка = 0; попытка * 2 < секунд; попытка += 1) {
		const состояние = await getFormState();
		const текст = текстСостояния(состояние);
		if (условие(текст, состояние)) {
			return текст;
		}
		await wait(2);
	}
	лог('  не дождались, состояние: ' + текстСостояния(await getFormState()));
	throw new Error('Не дождались: ' + описание);
}

// Подпись кнопки действия задается настройкой места запуска, поэтому ищем ее
// «от противного» — как единственную, не входящую в постоянный состав мастера.
async function кнопкаДействияМастера() {
	const служебные = ['Еще', '< Назад', 'Далее >', 'Далее', 'Открыть диалог', 'Закрыть',
		'Выгрузить пакет', 'Загрузить пакет', 'Открыть результат', 'Записать объект',
		'Основное', 'Процессы и задачи', 'Переписка', 'Журнал передачи'];
	const состояние = await getFormState();
	const имя = (состояние.buttons || [])
		.map(к => (typeof к === 'string' ? к : к.name))
		.filter(и => и && служебные.indexOf(и) < 0 && и.indexOf('Подменю') < 0
			&& и.indexOf('Группа') < 0 && и.indexOf('Форма') < 0)[0];
	if (!имя) {
		throw new Error('На странице результата нет кнопки действия: '
			+ JSON.stringify(состояние.buttons || []));
	}
	return имя;
}

// Грид отдает только отрисованное окно DOM, а строк у карты больше, чем
// помещается на экран. Поэтому после первого чтения грид прокручивается в
// конец и читается еще раз, а строки склеиваются по подписи реквизита.
async function прочитатьРекомендации() {
	const состояние = await getFormState();
	const грид = (состояние.tables || []).find(т => т.name === 'Рекомендации');
	const параметры = грид ? { maxRows: 60, table: грид.name } : { maxRows: 60 };
	const собранные = new Map();

	const первая = await readTable(параметры);
	for (const строка of (первая.rows || [])) {
		собранные.set(String(строка['Реквизит']), строка);
	}
	const последняя = (первая.rows || [])[(первая.rows || []).length - 1];
	if (последняя) {
		try {
			await clickElement(String(последняя['Реквизит']), грид ? { table: грид.name } : {});
			await getPage().keyboard.press('End');
			await wait(1);
			const вторая = await readTable(параметры);
			for (const строка of (вторая.rows || [])) {
				собранные.set(String(строка['Реквизит']), строка);
			}
		} catch (e) {
			лог('прокрутить рекомендации не вышло: ' + e.message);
		}
	}
	return [...собранные.values()];
}

// Колонку «Распознано» помощник пользователю больше не показывает: пустой ответ
// модели не распознан, а у распознанного есть предложенное значение.
function распознаноВСтроке(строка) {
	return !!строка && String(строка['Предлагается'] || '').trim() !== ''
		&& String(строка['Комментарий'] || '').indexOf('не найдено') < 0;
}

// Значения, совпадающие с объектом, помощник не отмечает. Чтобы действие
// действительно записало свойства, перед каждой фазой они очищаются.
async function очиститьСвойства() {
	const очистка = {};
	for (const подпись of Object.values(ПОЛЯ_КАРТОЧКИ)) {
		очистка[подпись] = '';
	}
	await clickElement('Свойства');
	await fillFields(очистка);
	await clickElement('Записать');
	await wait(2);
	лог('свойства в карточке очищены и записаны');
}

async function открытьКарточку() {
	await navigateLink('Справочник.ВнутренниеДокументы');
	await clickElement('Договор поставки', { dblclick: true });
	try { await clickElement('Напомнить позже'); } catch (e) { /* подсказка не всегда */ }
	лог('карточка открыта');
}

// Значения свойств на вкладке «Свойства» карточки: подпись -> представление.
async function свойстваКарточки() {
	await clickElement('Свойства');
	await wait(1);
	const состояние = await getFormState();
	const значения = {};
	for (const поле of (состояние.fields || [])) {
		const подпись = String(поле.label || '').replace(/:\s*$/, '').trim();
		if (подпись) {
			значения[подпись] = String(поле.value == null ? '' : поле.value).trim();
		}
	}
	return значения;
}

// Открывает помощник из карточки, запускает действие по текстовому файлу и
// возвращает строки рекомендаций.
async function разобратьФайл(действие) {
	const карточка = await getFormState();
	const подменю = (карточка.buttons || [])
		.map(кнопка => (typeof кнопка === 'string' ? кнопка : кнопка.name))
		.find(имя => имя && имя.indexOf('ПодменюЗаполнить') === 0);
	if (!подменю) {
		throw new Error('В карточке нет подменю «Заполнить» — обработка не зарегистрирована.');
	}
	await clickElement(подменю);

	await clickElement(действие);
	await wait(1);
	const список = await readTable({ maxRows: 20 });
	const колонка = (список.columns || [])[0];
	const файл = (список.rows || []).find(р => String(р[колонка] || '').indexOf('(текст)') >= 0);
	if (!файл) {
		throw new Error('Текстовое вложение не найдено: ' + JSON.stringify(список.rows || []));
	}
	await clickElement(String(файл[колонка]));
	лог('выбран файл: ' + файл[колонка]);
	for (const кнопка of ['Далее', 'Запустить анализ']) {
		try {
			await clickElement(кнопка);
			лог('нажато: ' + кнопка);
			break;
		} catch (e) {
			лог('кнопки «' + кнопка + '» нет, иду дальше');
		}
	}
	const итогАнализа = await дождаться(текст => текст.indexOf('Анализ завершен') >= 0, 240,
		'ответ модели (' + действие + ')');
	лог('анализ: ' + итогАнализа);

	const рекомендации = await прочитатьРекомендации();
	let распознано = 0;
	for (const имя of СВОЙСТВА) {
		const строка = рекомендации.find(р => String(р['Реквизит']) === имя);
		const текст = JSON.stringify(строка || null);
		лог('   ' + имя + ': ' + текст);
		проверить(строка && текст.indexOf('Нет среди значений') < 0 && текст.indexOf('несколько') < 0,
			'свойство «' + имя + '» дошло до предпросмотра без отказа ядра');
		if (распознаноВСтроке(строка)) {
			распознано += 1;
		}
	}
	// Распознавание зависит от модели, а не от ядра: считаем, но прогон не валим.
	лог('распознано моделью: ' + распознано + ' из ' + СВОЙСТВА.length);
	return рекомендации;
}

лог('=== прогон начат ===');

// --- 1. заполнение формы: свойства попадают в карточку и переживают запись ---

await открытьКарточку();
await очиститьСвойства();

const рекомендацииФормы = await разобратьФайл(ДЕЙСТВИЕ_ФОРМЫ);
const ожидаемые = {};
for (const [имяВКарте, подпись] of Object.entries(ПОЛЯ_КАРТОЧКИ)) {
	const строка = рекомендацииФормы.find(р => String(р['Реквизит']) === имяВКарте);
	if (распознаноВСтроке(строка)) {
		ожидаемые[подпись] = String(строка['Предлагается'] || '').trim();
	}
}

await clickElement(await кнопкаДействияМастера());
await clickElement('Да');
const итогФормы = await дождаться(
	текст => текст.indexOf('Заполнено') >= 0 || текст.indexOf('не приняла') >= 0,
	120,
	'итог заполнения формы');
лог('форма: ' + итогФормы);
проверить(итогФормы.indexOf('не принято: 0') >= 0, 'форма приняла все значения');
await clickElement('Закрыть');
await wait(1);

const послеЗаполнения = await свойстваКарточки();
лог('свойства после заполнения: ' + JSON.stringify(послеЗаполнения));
for (const [подпись, значение] of Object.entries(ожидаемые)) {
	проверить(послеЗаполнения[подпись] === значение,
		'в карточке «' + подпись + '» = «' + значение + '»');
}

await clickElement('Записать');
await wait(2);
await closeForm({ save: false });
await открытьКарточку();
const послеЗаписи = await свойстваКарточки();
лог('свойства после записи и повторного открытия: ' + JSON.stringify(послеЗаписи));
for (const [подпись, значение] of Object.entries(ожидаемые)) {
	проверить(послеЗаписи[подпись] === значение,
		'после записи «' + подпись + '» = «' + значение + '»');
}
проверить(Object.keys(ожидаемые).length > 0, 'модель распознала хотя бы одно свойство-список');
await closeForm({ save: false });

// --- 2. запись в объект: без отказов по одноименным и без чужих значений ------

await открытьКарточку();
await очиститьСвойства();
await разобратьФайл(ДЕЙСТВИЕ_ЗАПИСИ);

const кнопка = await кнопкаДействияМастера();
лог('кнопка действия: ' + кнопка);
await clickElement(кнопка);
await clickElement('Да');

const итогЗаписи = await дождаться(
	текст => текст.indexOf('Применено') >= 0 || текст.indexOf('Отклонено') >= 0
		|| текст.indexOf('Ошибка') >= 0,
	120,
	'итог записи в объект');
лог('запись: ' + итогЗаписи);
проверить(итогЗаписи.indexOf('Применено') >= 0, 'действие записало значения в объект');

// Причины отказов помощник выводит сообщениями, а не в поля формы.
const состояниеЗаписи = await getFormState();
const сообщения = JSON.stringify(((состояниеЗаписи.errors || {}).messages) || []);
лог('сообщения: ' + сообщения);
проверить(сообщения.indexOf('несколько') < 0, 'одноименное свойство не отклонено');
проверить(сообщения.indexOf('относится к другому свойству') < 0, 'чужих значений в плане нет');

await closeForm({ save: false });
try { await closeForm({ save: false }); } catch (e) { /* карточка могла закрыться сама */ }

лог('');
if (проблемы.length > 0) {
	throw new Error('Провалов: ' + проблемы.length + ' — ' + проблемы.join('; '));
}
лог('[OK] Дополнительные реквизиты-списки работают.');
