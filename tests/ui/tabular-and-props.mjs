// Проверка табличных частей и дополнительных реквизитов: модель возвращает
// массив строк «Стороны» и значение свойства «Предмет договора», помощник
// показывает их построчно, а действие раскладывает по строкам объекта.
//
// Сценарий ходит в живую базу и обращается к модели, поэтому в обычный прогон
// UI-смоука не входит: запускается руками при правке этой ветки кода.
//
//   node run.mjs run http://localhost:8081/do21 tests/ui/tabular-and-props.mjs
//
// Перед прогоном карта «Реквизиты договора» должна содержать поля табличной
// части «Стороны» и поле дополнительного реквизита, а схема — быть перенесена
// в сценарий (команда «Обновить схему в сценариях» на форме карты).

const ЖУРНАЛ = 'H:\\1C\\xml\\LLM_Subsystem_test\\.build\\tabular-and-props.log';
const ДЕЙСТВИЕ_ЗАПИСИ = 'Разобрать пачку договоров';
const ДЕЙСТВИЕ_ФОРМЫ = 'Извлечь реквизиты из файла';
const проблемы = [];

function лог(текст) {
	const строка = new Date().toISOString().slice(11, 19) + '  ' + текст + '\n';
	try { writeFileSync(ЖУРНАЛ, строка, { flag: 'a' }); } catch (e) { /* журнал не обязателен */ }
	console.log(текст);
}

function проверить(условие, что) {
	лог((условие ? '  [ok]   ' : '  [ФЕЙЛ] ') + что);
	if (!условие) проблемы.push(что);
}

function текстСостояния(состояние) {
	return JSON.stringify(состояние.fields || []);
}

async function дождаться(условие, секунд, описание) {
	лог('жду: ' + описание);
	for (let попытка = 0; попытка * 2 < секунд; попытка += 1) {
		const состояние = await getFormState();
		const текст = текстСостояния(состояние);
		if (условие(текст, состояние)) {
			return текст;
		}
		await wait(2);
	}
	лог('  не дождались, состояние: ' + текстСостояния(await getFormState()));
	throw new Error('Не дождались: ' + описание);
}

// Подпись кнопки действия задается настройкой места запуска, поэтому ищем ее
// «от противного» — как единственную, не входящую в постоянный состав мастера.
async function кнопкаДействияМастера() {
	const служебные = ['Еще', '< Назад', 'Далее >', 'Далее', 'Открыть диалог', 'Закрыть',
		'Выгрузить пакет', 'Загрузить пакет', 'Открыть результат', 'Записать объект',
		'Основное', 'Процессы и задачи', 'Переписка', 'Журнал передачи'];
	const состояние = await getFormState();
	const имя = (состояние.buttons || [])
		.map(к => (typeof к === 'string' ? к : к.name))
		.filter(и => и && служебные.indexOf(и) < 0 && и.indexOf('Подменю') < 0
			&& и.indexOf('Группа') < 0 && и.indexOf('Форма') < 0)[0];
	if (!имя) {
		throw new Error('На странице результата нет кнопки действия: '
			+ JSON.stringify(состояние.buttons || []));
	}
	return имя;
}

async function запуститьДействие(имя) {
	await clickElement(имя);
	await wait(1);
	// Текстовое вложение выбираем по содержимому строки таблицы: обрывок текста
	// клик по списку не находит.
	const список = await readTable({ maxRows: 20 });
	const колонка = (список.columns || [])[0];
	const строка = (список.rows || [])
		.find(р => String(р[колонка] || '').indexOf('(текст)') >= 0);
	if (строка) {
		await clickElement(String(строка[колонка]));
		лог('выбран файл: ' + строка[колонка]);
	} else {
		throw new Error('Текстовое вложение не найдено: ' + JSON.stringify(список.rows || []));
	}
	for (const кнопка of ['Далее', 'Запустить анализ']) {
		try {
			await clickElement(кнопка);
			лог('нажато: ' + кнопка);
			break;
		} catch (e) {
			лог('кнопки «' + кнопка + '» нет, иду дальше');
		}
	}
	await дождаться(текст => текст.indexOf('Анализ завершен') >= 0, 210, 'ответ модели (' + имя + ')');
}

// Таблица рекомендаций — не тот грид, что список файлов, поэтому выбираем его
// по имени из состава формы.
//
// Грид отдает только отрисованное окно DOM, а строк у карты с табличной частью
// заведомо больше, чем помещается на экран. Поэтому после первого чтения грид
// прокручивается в конец и читается еще раз, а строки склеиваются.
async function прочитатьРекомендации() {
	const состояние = await getFormState();
	const грид = (состояние.tables || []).find(т => т.name === 'Рекомендации');
	const параметры = грид ? { maxRows: 40, table: грид.name } : { maxRows: 40 };
	const собранные = new Map();

	const первая = await readTable(параметры);
	лог('колонки рекомендаций: ' + JSON.stringify(первая.columns || []));
	for (const строка of (первая.rows || [])) {
		собранные.set(String(строка['Реквизит']), строка);
	}

	const последняя = (первая.rows || [])[(первая.rows || []).length - 1];
	if (последняя) {
		try {
			await clickElement(String(последняя['Реквизит']), грид ? { table: грид.name } : {});
			await getPage().keyboard.press('End');
			await wait(1);
			const вторая = await readTable(параметры);
			for (const строка of (вторая.rows || [])) {
				собранные.set(String(строка['Реквизит']), строка);
			}
		} catch (e) {
			лог('прокрутить рекомендации не вышло: ' + e.message);
		}
	}

	for (const строка of собранные.values()) {
		лог('   ' + JSON.stringify(строка));
	}
	return [...собранные.values()];
}

async function открытьПомощника() {
	const карточка = await getFormState();
	const подменю = (карточка.buttons || [])
		.map(кнопка => (typeof кнопка === 'string' ? кнопка : кнопка.name))
		.find(имя => имя && имя.indexOf('ПодменюЗаполнить') === 0);
	if (!подменю) {
		throw new Error('В карточке нет подменю «Заполнить» — обработка не зарегистрирована.');
	}
	await clickElement(подменю);
}

лог('=== прогон начат ===');

